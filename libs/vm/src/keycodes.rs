pub(crate) fn qemu_keycode(linux: u32) -> Option<u32> {
    if (1..=IDENTICAL).contains(&linux) {
        return Some(linux);
    }
    let index = usize::try_from(linux.checked_sub(IDENTICAL + 1)?).ok()?;
    FROM_LINUX
        .get(index)
        .copied()
        .filter(|code| *code != 0)
        .map(u32::from)
}
